"""Build the index in findings/README.md from each entry's front matter.

Usage: python scripts/build_findings_index.py          rewrite the index
       python scripts/build_findings_index.py --check  exit 1 if the index is stale
Front matter (top of findings/<topic>.md): topic, area, question, checked
(YYYY-MM-DD), review_months (default 12), status (current | superseded | archived).
"""
import re, sys, datetime
from pathlib import Path

DIR = Path(__file__).resolve().parent.parent / "findings"
README = DIR / "README.md"
START, END = "<!-- index:start -->", "<!-- index:end -->"
AREAS = ["Software process", "Agent setup", "Research methods", "ML systems", "Career"]


def front(path):
    t = path.read_text(encoding="utf-8")
    m = re.match(r"---\r?\n(.*?)\r?\n---\r?\n", t, re.S)
    if not m:
        raise SystemExit(f"{path.name}: no front matter")
    d = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        d[k.strip()] = v.strip()
    for k in ("topic", "area", "question", "checked"):
        if not d.get(k):
            raise SystemExit(f"{path.name}: missing {k}")
    if d["topic"] != path.stem:
        raise SystemExit(f"{path.name}: topic {d['topic']} != file name")
    if d["area"] not in AREAS:
        raise SystemExit(f"{path.name}: unknown area {d['area']}")
    d.setdefault("review_months", "12")
    d.setdefault("status", "current")
    if d["status"] not in ("current", "superseded", "archived"):
        raise SystemExit(f"{path.name}: bad status {d['status']}")
    return d


def review_by(d):
    y, m, day = map(int, d["checked"].split("-"))
    n = m - 1 + int(d["review_months"])
    return datetime.date(y + n // 12, n % 12 + 1, min(day, 28)).isoformat()


def row(d):
    q = d["question"].replace("|", "\\|")
    return f"| [{d['topic']}]({d['topic']}.md) | {q} | {d['checked']} | {review_by(d)} |"


def build():
    es = [front(p) for p in sorted(DIR.glob("*.md")) if p.name != "README.md"]
    head = "| Topic | Question | Checked | Review by |\n|---|---|---|---|"
    out = ["Generated by `scripts/build_findings_index.py` from each entry's front matter; never edit by hand.", ""]
    for a in AREAS:
        cur = sorted((e for e in es if e["area"] == a and e["status"] == "current"), key=lambda e: e["checked"])
        out += [f"### {a}", "", head] + [row(e) for e in cur] + [""]
    old = [e for e in es if e["status"] != "current"]
    if old:
        out += ["### Superseded or archived (do not answer from these)", "", head]
        out += [row(e) for e in sorted(old, key=lambda e: e["topic"])] + [""]
    return "\n".join(out)


def main():
    t = README.read_text(encoding="utf-8")
    i, j = t.index(START), t.index(END)
    new = t[: i + len(START)] + "\n" + build() + "\n" + t[j:]
    if "--check" in sys.argv:
        if new.replace("\r\n", "\n") != t.replace("\r\n", "\n"):
            print("findings index is stale: run scripts/build_findings_index.py")
            sys.exit(1)
        return
    README.write_text(new, encoding="utf-8", newline="")


main()
